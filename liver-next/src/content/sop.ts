/**
 * The production playbook.
 *
 * Written down because the alternative is that it lives in one person's head,
 * which is fine until two events run on the same Thursday. Every item here is
 * a decision that has already been made once, and writing it down is what
 * turns it from a thing somebody remembers into a thing anybody can do.
 *
 * The bias throughout is towards the things that are invisible until they are
 * missing. Nobody forgets the chuppah. What gets forgotten is the second
 * generator, the meal for the photographers, the lighting on the path back to
 * the car park, and the phone number of whoever holds the key.
 *
 * Content, not data. It ships with the app rather than sitting in a table
 * because it is the same for every event and every producer, it needs no
 * migration to change, and it is reviewable in a diff like any other writing.
 */

export type SopItem = {
  /** The instruction, in the imperative, because it is a thing to do. */
  text: string;
  /** Why, when the why is not obvious. Left out when it is. */
  why?: string;
  /** When this happens, relative to the event. */
  when?: string;
};

export type SopSection = {
  id: string;
  title: string;
  sub: string;
  items: SopItem[];
};

export type SopChapter = {
  id: string;
  title: string;
  sub: string;
  sections: SopSection[];
};

