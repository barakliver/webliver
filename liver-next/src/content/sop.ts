/** Every item, flattened, for searching. Built once at module load rather than
 *  on each keystroke: it is a fixed list and rebuilding it per character is
 *  work nobody asked for. */
export const SOP_INDEX = SOP.flatMap((chapter) =>
  chapter.sections.flatMap((section) =>
    section.items.map((item, i) => ({
      key: `${section.id}-${i}`,
      chapterId: chapter.id,
      chapterTitle: chapter.title,
      sectionId: section.id,
      sectionTitle: section.title,
      item,
      haystack: `${chapter.title} ${section.title} ${item.text} ${item.why ?? ''} ${item.when ?? ''}`,
    }))
  )
);

export const sopItemCount = SOP_INDEX.length;
