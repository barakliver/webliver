/**
 * The operating book: how to run the system, for the two people inside it.
 *
 * The playbook in sop.ts answers "how do we produce an event". This book
 * answers a smaller and more frequent question: "where do I press". It exists
 * because the first hour inside any system is spent not knowing what the
 * screens are for, and because the questions people actually ask are "how do
 * I add a guest", not "explain the guests module".
 *
 * So the shape is the shape of the question. Every entry is one question, the
 * way a person asks it, answered in numbered steps that name the real screens
 * and the real buttons. The first chapter of each book is not questions at
 * all: it is the order to do things in, because a new arrival's problem is
 * not that they cannot find the answer, it is that they do not yet know what
 * to ask.
 *
 * Two books, because the two people see two different systems. The producer's
 * book walks the whole console; the couple's book walks their personal area,
 * and it exists in both languages because the personal area does.
 *
 * White label rule: no person's name anywhere in here. The book says "the
 * production" and "your producer", so it reads correctly under any tenant's
 * brand.
 *
 * Content, not data, for the same reason the playbook is: it is the same for
 * everyone, it changes by diff, and the concierge reads it at build time to
 * learn how to direct people (see lib/ai/concierge.ts).
 */

